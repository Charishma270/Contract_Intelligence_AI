import re
import unicodedata


# ---------------------------------------------------------
# OCR Cleaning
# ---------------------------------------------------------

def clean_text(text):

    if not text:

        return ""

    # -----------------------------------------------------
    # Unicode normalization
    # -----------------------------------------------------

    text = unicodedata.normalize(
        "NFKC",
        text
    )

    # -----------------------------------------------------
    # Remove page numbers
    # -----------------------------------------------------

    text = re.sub(

        r'\bPage\s+\d+\b',

        ' ',

        text,

        flags=re.IGNORECASE
    )

    # -----------------------------------------------------
    # Remove standalone numbers
    # -----------------------------------------------------

    text = re.sub(

        r'\n\s*\d+\s*\n',

        '\n',

        text
    )

    # -----------------------------------------------------
    # Remove OCR artifacts
    # -----------------------------------------------------

    text = re.sub(

        r'[_•■◆►]+',

        ' ',

        text
    )

    # -----------------------------------------------------
    # Preserve legal punctuation
    # -----------------------------------------------------

    text = re.sub(

        r'[^\w\s\.,;:\-\(\)/]',

        ' ',

        text
    )

    # -----------------------------------------------------
    # Fix broken spacing
    # -----------------------------------------------------

    text = re.sub(

        r'\s+',

        ' ',

        text
    )

    # -----------------------------------------------------
    # Remove repeated headers
    # -----------------------------------------------------

    text = re.sub(

        r'(confidential|draft copy)',

        ' ',

        text,

        flags=re.IGNORECASE
    )

    return text.strip()